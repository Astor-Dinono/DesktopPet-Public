#!/usr/bin/env python3
"""Compile the shared, reviewed yawn vectors into dependency-free C++ data.

Only numeric drawing data is emitted. Source paths and provenance metadata from
the JSON stay out of the executable and generated header.
"""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "Sources/DesktopPet/Resources/DogYawn.json"


def compile_artwork(source):
    if source.get("version") != 1 or len(source.get("frames", [])) != 97:
        raise ValueError("Expected the reviewed version 1, 97-frame artwork")
    duration = source["duration"]
    if not math.isfinite(duration) or duration != 4.062548752834467:
        raise ValueError("Unexpected yawn duration")
    tip = source["tailTip"]
    if len(tip) != 2 or not all(math.isfinite(n) for n in tip):
        raise ValueError("Invalid tail anchor")
    commands, layers, frames = [], [], []

    def path(values):
        offset, index, opened = len(commands), 0, False
        while index < len(values):
            command = values[index]
            index += 1
            if command == 2:
                if not opened:
                    raise ValueError("Close without a path")
                opened = False
            elif command in (0, 1):
                if index + 1 >= len(values) or (command == 1 and not opened):
                    raise ValueError("Invalid path segment")
                for n in values[index:index + 2]:
                    if not math.isfinite(n) or n != int(n) or not -32768 <= n <= 32767:
                        raise ValueError("Path coordinate does not fit the reviewed integer format")
                index += 2
                opened = True
            else:
                raise ValueError("Unknown path command")
        if opened:
            raise ValueError("Recorded fill paths must be closed")
        commands.extend(int(n) for n in values)
        return "{%d,%d}" % (offset, len(values))

    for index, frame in enumerate(source["frames"]):
        time, height, width, center = (frame[k] for k in ("t", "h", "w", "x"))
        if (not all(math.isfinite(n) for n in (time, height, width, center))
                or time != index / 24 or time > duration or width <= 0 or height >= 696):
            raise ValueError("Invalid recorded frame")
        face, layer_offset = path(frame["face"]), len(layers)
        for layer in frame["colors"]:
            color = layer["fill"]
            if not isinstance(color, int) or not 0 <= color <= 0xffffff:
                raise ValueError("Invalid fill color")
            layers.append("{0x%06xu,%s}" % (color, path(layer["path"])))
        frames.append("{%s,%s,%s,%s,%s,%d,%d}" % (
            repr(float(time)), repr(float(height)), repr(float(width)), repr(float(center)),
            face, layer_offset, len(layers) - layer_offset))
    lines = [
        "// Generated by windows/tools/generate_yawn.py; do not edit.",
        "#pragma once", "#include <array>", "#include <cstddef>", "#include <cstdint>",
        "namespace dog::yawn_data {",
        "struct Path { std::size_t offset,count; };",
        "struct Layer { std::uint32_t fill; Path path; };",
        "struct Frame { double time,height,width,center; Path face; std::size_t layerOffset,layerCount; };",
        "inline constexpr double duration=" + repr(duration) + ";",
        "inline constexpr std::array<double,2> tailTip{{" + ",".join(map(repr, tip)) + "}};",
        "inline constexpr std::int16_t commands[]={",
    ]
    lines += [",".join(map(str, commands[i:i + 36])) + "," for i in range(0, len(commands), 36)]
    lines += ["};", "inline constexpr Layer layers[]={", *[s + "," for s in layers], "};",
              "inline constexpr std::array<Frame,97> frames{{", *[s + "," for s in frames],
              "}};", "} // namespace dog::yawn_data", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generated = compile_artwork(json.loads(args.source.read_text()))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text() != generated:
        args.output.write_text(generated)
    print("Compiled 97 yawn frames:", args.output)


if __name__ == "__main__":
    main()
